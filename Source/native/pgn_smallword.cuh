template <unsigned P, unsigned Inv240, unsigned R64Mod>
__device__ __forceinline__ uint32_t firstPhase(uint64_t low, uint64_t high) {
    const uint32_t r = uint32_t(((high % P) * R64Mod + (low % P)) % P);
    return (r * Inv240) % P;
}
template <unsigned P> __device__ __forceinline__ uint32_t nextPhase(uint32_t v) {
    v += 8192u % P;
    return v >= P ? v - P : v;
}
template <unsigned P> __device__ __forceinline__ uint32_t firstIndex(uint32_t phase) {
    const uint32_t s = phase + threadIdx.x % P;
    return s >= P ? s - P : s;
}
template <unsigned P> __device__ __forceinline__ uint32_t nextIndex(uint32_t v) {
    v += 512u % P;
    return v >= P ? v - P : v;
}
