__device__ __forceinline__ uint32_t phase(uint64_t low, uint64_t high) {
    constexpr uint64_t M = 30030, R64 = (UINT64_MAX % M + 1) % M;
    // Reduce the high limb before multiplying: exact for every128-bit class30 origin.
    return uint32_t(((low % M + (high % M) * R64) % M) / 30);
}
__device__ __forceinline__ uint32_t advance(uint32_t phase) {
    phase += 65536u % 1001u;
    return phase >= 1001 ? phase - 1001 : phase;
}
__device__ __forceinline__ uint64_t word(uint32_t phase, unsigned offset) {
    const unsigned at = (phase + 8u * offset) % 1001u, shift = (at & 7u) * 8u;
    const uint64_t a = __ldg(masks + (at >> 3)), b = __ldg(masks + (at >> 3) + 1);
    return (a >> shift) | (shift ? b << (64 - shift) : 0);
}
